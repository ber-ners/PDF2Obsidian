import type { TFile, Vault } from 'obsidian';

/**
 * Normalized bounding box coordinates [x0, y0, x1, y1]
 * where all coordinates are clamped integers in the range [0, 1000].
 */
export type NormalizedBbox = [number, number, number, number];

/**
 * MinerU layout item representation from content_list.json.
 */
export interface MineruContentItem {
  page_idx: number;
  type: string;
  bbox?: [number, number, number, number];
  text?: string;
  text_level?: number;
  table_body?: string;
  table_caption?: string[] | string;
  table_footnote?: string[] | string;
  img_path?: string;
  image_caption?: string[] | string;
  image_footnote?: string[] | string;
  list_items?: string[];
  continuationOf?: string;
  [key: string]: unknown;
}

/**
 * Result of MinerU PDF layout extraction.
 */
export interface MineruExtractResult {
  markdown: string;
  contentList: MineruContentItem[];
  images: Record<string, Uint8Array>;
  rawZipBuffer?: ArrayBuffer | Uint8Array;
}

/**
 * Configuration for MinerU extraction client.
 */
export interface MineruClientConfig {
  mode?: 'official' | 'remote';
  cloudApiUrl?: string;
  cloudApiToken?: string;
  remoteApiUrl?: string;
  modelVersion?: 'pipeline' | 'vlm';
  enableFormula?: boolean;
  enableTable?: boolean;
  enableImageAnalysis?: boolean;
  pollIntervalMs?: number;
  timeoutMs?: number;
  onProgress?: (status: string) => void;
}

/**
 * Configuration for LLM translation and summarization client.
 */
export interface LlmClientConfig {
  provider?: 'openai' | 'deepseek' | 'openai-compatible' | 'ollama';
  baseUrl?: string;
  apiKey?: string;
  model?: string;
  chunkCharLimit?: number;
  timeoutMs?: number;
  temperature?: number;
  maxRetries?: number;
  onProgress?: (status: string) => void;
}

/**
 * Single Markdown chunk for translation.
 */
export interface MarkdownChunk {
  index: number;
  headingPath: string[];
  content: string;
}

/**
 * Result of Markdown chunked translation.
 */
export interface TranslationResult {
  translatedMarkdown: string;
  chunks: Array<{
    index: number;
    headingPath: string[];
    charCount: number;
    translatedContent: string;
  }>;
}

/**
 * Generated academic reading assets.
 */
export interface ReadingAssetsResult {
  summary: string;
  terms: string;
  qa: string;
}

/**
 * Structured academic paper metadata stored in Obsidian note YAML frontmatter.
 */
export interface PaperMetadata {
  title: string;
  translatedTitle?: string;
  authors?: string[];
  year?: number;
  venue?: string;
  doi?: string;
  arxivId?: string;
  slug?: string;
  keywords?: string[];
  tags?: string[];
  sourceHash?: string;
  sourcePdf?: string;
  originalNote?: string;
  translatedNote?: string;
  bilingualNote?: string;
  indexNote?: string;
  summaryNote?: string;
  termsNote?: string;
  qaNote?: string;
  type?: string;
  parent?: string;
  lang?: string[] | string;
  createdAt?: string;
  [key: string]: unknown;
}

/**
 * Input parameters for the full paper import pipeline.
 */
export interface ImportPipelineInput {
  vault: Vault;
  pdfData: ArrayBuffer | Uint8Array;
  pdfFileName: string;
  metadata?: Partial<PaperMetadata>;
  targetFolder?: string;
  mineruConfig: MineruClientConfig;
  llmConfig?: LlmClientConfig;
  skipTranslation?: boolean;
  skipReadingAssets?: boolean;
  onProgress?: (step: string, percent?: number) => void;
}

/**
 * Persisted asset references generated by the import pipeline.
 */
export interface ImportPipelineResult {
  folderPath: string;
  slug: string;
  metadata: PaperMetadata;
  indexFile: TFile;
  bilingualFile: TFile;
  originalFile: TFile;
  translatedFile?: TFile;
  summaryFile?: TFile;
  termsFile?: TFile;
  qaFile?: TFile;
  layoutFile: TFile;
  pdfFile: TFile;
  imageFiles: TFile[];
}
