import esbuild from 'esbuild';
import process from 'node:process';
import { readFile, copyFile, unlink, access } from 'node:fs/promises';
import { createRequire, builtinModules } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const prod = process.argv.includes('production') || process.env.NODE_ENV === 'production';
const isWatch = process.argv.includes('--watch') || process.argv.includes('-w') || process.argv[2] === 'watch';

/**
 * Plugin to inline pdf.worker.min.mjs into the bundle as a string literal.
 */
const inlinePdfWorkerPlugin = {
  name: 'inline-pdf-worker',
  setup(build) {
    build.onResolve({ filter: /^(inline-pdfjs-worker|pdfjs-dist\/build\/pdf\.worker(\.min)?\.mjs)$/ }, (args) => ({
      path: args.path,
      namespace: 'pdf-worker-ns'
    }));

    build.onLoad({ filter: /.*/, namespace: 'pdf-worker-ns' }, async () => {
      let workerPath = null;
      const candidates = [
        () => {
          const req = createRequire(import.meta.url);
          const pdfjsPkg = dirname(req.resolve('pdfjs-dist/package.json'));
          return join(pdfjsPkg, 'build/pdf.worker.min.mjs');
        },
        () => {
          const req = createRequire(join(__dirname, '../../apps/desktop-web/package.json'));
          const pdfjsPkg = dirname(req.resolve('pdfjs-dist/package.json'));
          return join(pdfjsPkg, 'build/pdf.worker.min.mjs');
        },
        () => join(__dirname, '../../apps/desktop-web/public/pdf.worker.min.mjs'),
        () => join(__dirname, '../../node_modules/.pnpm/pdfjs-dist@4.10.38/node_modules/pdfjs-dist/build/pdf.worker.min.mjs')
      ];

      for (const getPath of candidates) {
        try {
          const candidatePath = getPath();
          await access(candidatePath);
          workerPath = candidatePath;
          break;
        } catch {
          // Continue searching candidates
        }
      }

      if (!workerPath) {
        throw new Error('Unable to locate pdf.worker.min.mjs in workspace dependencies');
      }

      const contents = await readFile(workerPath, 'utf8');
      return {
        contents,
        loader: 'text'
      };
    });
  }
};

/**
 * Plugin to rename main.css to styles.css (or compile styles/styles.css if main.css was omitted).
 */
const cssRenamerPlugin = {
  name: 'css-renamer',
  setup(build) {
    build.onEnd(async () => {
      const mainCss = join(__dirname, 'main.css');
      const stylesCss = join(__dirname, 'styles.css');
      try {
        await access(mainCss);
        await copyFile(mainCss, stylesCss);
        await unlink(mainCss);
        console.log('[esbuild] Emitted styles.css (renamed from main.css)');
      } catch {
        // Fallback: compile styles/styles.css directly if main.css was not produced
        try {
          await esbuild.build({
            entryPoints: [join(__dirname, 'styles/styles.css')],
            bundle: true,
            outfile: stylesCss,
            loader: {
              '.woff2': 'dataurl',
              '.woff': 'dataurl',
              '.ttf': 'dataurl'
            },
            logLevel: 'silent'
          });
          console.log('[esbuild] Emitted styles.css (compiled directly from styles/styles.css)');
        } catch (err) {
          console.error('[esbuild] Warning: Could not generate styles.css:', err);
        }
      }
    });
  }
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
PDF2obsidian Obsidian Plugin
*/
`;

const footer = `if (typeof module !== 'undefined' && module.exports && module.exports.default) {
  module.exports = Object.assign(module.exports.default, module.exports);
}
`;

const context = await esbuild.context({
  banner: { js: banner },
  footer: { js: footer },
  entryPoints: [join(__dirname, 'src/main.ts')],
  bundle: true,
  alias: {
    fflate: join(__dirname, '../../node_modules/.pnpm/fflate@0.8.3/node_modules/fflate/esm/browser.js')
  },
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`)
  ],
  format: 'cjs',
  target: 'es2022',
  platform: 'browser',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  minify: prod,
  treeShaking: true,
  outfile: join(__dirname, 'main.js'),
  jsx: 'automatic',
  define: {
    'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development')
  },
  loader: {
    '.woff2': 'dataurl',
    '.woff': 'dataurl',
    '.ttf': 'dataurl'
  },
  plugins: [inlinePdfWorkerPlugin, cssRenamerPlugin]
});

if (isWatch) {
  console.log('[esbuild] Watching for changes...');
  await context.watch();
} else {
  await context.rebuild();
  await context.dispose();
  console.log('[esbuild] Build complete.');
}
